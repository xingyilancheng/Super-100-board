// Independently lay out all 100 snake cells; do not use production geometry helpers.
const RACE_POINTS = {};
for (let row = 0; row < 10; row++) {
  const numbers = sequence(row * 10 + 1, row * 10 + 10);
  if (row % 2) numbers.reverse();
  numbers.forEach((cell, col) => { RACE_POINTS[cell] = [col, row]; });
}
function segmentsIntersect(a, b, c, d) {
  const cross = (p, q, r) => (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0]);
  const boxesOverlap = [0, 1].every(axis =>
    Math.max(Math.min(a[axis], b[axis]), Math.min(c[axis], d[axis])) <=
    Math.min(Math.max(a[axis], b[axis]), Math.max(c[axis], d[axis])));
  return boxesOverlap && cross(a, b, c) * cross(a, b, d) <= 0 && cross(c, d, a) * cross(c, d, b) <= 0;
}
function checkRaceBoard(level) {
  const { ladders, traps } = level, stage = level.id - 216;
  assert(Array.isArray(ladders) && Array.isArray(traps));
  assert.equal(ladders.length, RACE_LADDERS[stage], 'Exact ladder count, never best-effort');
  assert.equal(traps.length, RACE_TRAPS[stage], 'Exact trap count');
  const endpoints = [];
  for (const ladder of ladders) {
    assert.deepEqual(Object.keys(ladder).sort(), ['from', 'to']);
    const { from, to } = ladder;
    assert([from, to].every(n => Number.isInteger(n) && n >= 2 && n <= 99));
    assert(to > from, 'Ladders advance numerically');
    const [x1, y1] = RACE_POINTS[from], [x2, y2] = RACE_POINTS[to];
    assert.equal(Math.abs(x1 - x2), 1, 'Exactly one visual snake column apart');
    assert([1, 2].includes(Math.abs(y1 - y2)), 'One or two rows apart');
    endpoints.push(from, to);
  }
  assert.equal(new Set(endpoints).size, endpoints.length, 'All ladder endpoints are unique');
  for (let i = 0; i < ladders.length; i++) {
    for (let j = i + 1; j < ladders.length; j++) {
      assert(!segmentsIntersect(RACE_POINTS[ladders[i].from], RACE_POINTS[ladders[i].to],
        RACE_POINTS[ladders[j].from], RACE_POINTS[ladders[j].to]), 'Ladder segments must not cross or touch');
    }
  }
  assert.equal(new Set(traps).size, traps.length);
  for (const trap of traps) {
    assert(Number.isInteger(trap) && trap >= 11 && trap <= 98, 'Trap can retreat ten without leaving the board');
    assert(!endpoints.includes(trap), 'No trap overlaps either ladder endpoint');
    assert(traps.every(other => other === trap || Math.abs(other - trap) >= 5), 'Traps are not clustered');
  }
  if (stage > 0) {
    for (const [low, high] of [[2, 30], [31, 70], [71, 99]]) {
      assert(endpoints.some(cell => cell >= low && cell <= high), 'Ladders spread across the board');
      assert(traps.some(cell => cell >= low && cell <= high), 'Traps spread across the board');
    }
  }
}

