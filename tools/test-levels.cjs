function checkPattern(level) {
  const { id } = level;
  assert.equal(level.kind, 'pattern');
  assert.equal(level.interaction, 'fill');
  assert.equal(level.size, 10);
  const stage = id - 16;
  const active = level.activeCells;
  assert.deepEqual(active, active.slice().sort((a, b) => a - b), 'Active cells sorted');
  assert.equal(new Set(active).size, active.length);
  assert.equal(active.length, [5, 6, 7, 8, 9][stage], 'Pattern grows each level');
  assert.equal(level.blanks.length, active.length - 1, 'Exactly one provided number');
  for (const cell of sequence(1, 100)) {
    assert.equal(level.values[cell], active.includes(cell) ? cell : null, `Pattern value ${id}/${cell}`);
  }
  assert.equal(level.givens.length, 1);
  const given = level.givens[0];
  assert(active.includes(given), 'The provided number is part of the pattern');
  assert(!level.blanks.includes(given));
  assert.deepEqual(level.blanks, active.filter(cell => cell !== given), 'Blanks are the rest of the pattern');
  assert.deepEqual(level.fillOrder, level.blanks);
  assert.deepEqual(ownKeys(level.answers), level.blanks);
  assert.deepEqual(ownKeys(level.clues), level.blanks);
  for (const cell of level.blanks) {
    assert.equal(level.answers[cell], cell, 'Identity hundred-chart answers');
    assert(level.clues[cell].length > 0);
  }
  // Every blank must be reachable from the given by orthogonal steps inside the pattern,
  // so the single provided number is enough to deduce the whole shape.
  const reachable = new Set([given]);
  let grew = true;
  while (grew) {
    grew = false;
    for (const cell of active) {
      if (reachable.has(cell)) continue;
      const linked = [cell - 10, cell + 10, colOf(cell) > 0 ? cell - 1 : NaN, colOf(cell) < 9 ? cell + 1 : NaN]
        .some(p => active.includes(p) && reachable.has(p));
      if (linked) { reachable.add(cell); grew = true; }
    }
  }
  assert.equal(reachable.size, active.length, `Pattern is connected through the given: ${id}`);
  if (id === 16) {
    assert.equal(new Set(active.map(colOf)).size, 3);
    assert(active.includes(given - 10) && active.includes(given + 10) && active.includes(given - 1) && active.includes(given + 1),
      'Level 16 is the four orthogonal neighbours of the given');
  }
}

