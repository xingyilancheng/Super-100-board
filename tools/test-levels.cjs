// Enumerate by row/column geometry, without production moves/costs or a DAG recurrence.
function allRightDownRoutes() {
  const routes = [], route = [];
  function walk(row, col) {
    route.push(row * 10 + col + 1);
    if (row === 9 && col === 9) routes.push(route.slice());
    else {
      if (row < 9) walk(row + 1, col);
      if (col < 9) walk(row, col + 1);
    }
    route.pop();
  }
  walk(0, 0);
  return routes;
}
const ROUTES = allRightDownRoutes();
assert.equal(ROUTES.length, 48620);
assert(ROUTES.every(route => route.length === 19 && route[0] === 1 && route[18] === 100));

// Every possible suffix occurs in at least one full route. Independently enumerate suffixes
// for ALL (head, checkpointIndex) states, including states off any globally optimal route.
function bruteMaze(givens, checkpoints) {
  const free = new Set(givens), count = checkpoints.length;
  const costs = Array.from({ length: count + 1 }, () => new Array(101).fill(Infinity));
  const moves = Array.from({ length: count + 1 }, () => Array.from({ length: 101 }, () => new Set()));
  for (const route of ROUTES) {
    const checkpointPositions = checkpoints.map(cell => route.indexOf(cell));
    let futureCost = 0;
    for (let position = 18; position >= 0; position--) {
      const head = route[position];
      for (let index = 0; index <= count; index++) {
        let lastPosition = position, valid = true;
        for (let pending = index; pending < count; pending++) {
          if (checkpointPositions[pending] <= lastPosition) { valid = false; break; }
          lastPosition = checkpointPositions[pending];
        }
        if (!valid || futureCost > costs[index][head]) continue;
        if (futureCost < costs[index][head]) {
          costs[index][head] = futureCost;
          moves[index][head].clear();
        }
        if (position < 18) moves[index][head].add(route[position + 1]);
      }
      if (!free.has(head)) futureCost++;
    }
  }
  return { costs, moves };
}
