function checkJump(level) {
  const blanks = level.blanks;
  assert(level.goal.includes('跳'), `Jump-chapter goal mentions jumping: ${level.id}`);
  if (level.id === 12) {
    assert.equal(blanks.length, 5);
    assert.equal(new Set(blanks.map(colOf)).size, 1, 'Vertical jump stays in one column');
    for (let i = 1; i < blanks.length; i++) assert.equal(blanks[i] - blanks[i - 1], 20, 'Skip a row: +20');
  } else if (level.id === 13) {
    assert.equal(blanks.length, 5);
    for (let i = 1; i < blanks.length; i++) assert.equal(blanks[i] - blanks[i - 1], 11, 'Diagonal jump: +11');
  } else if (level.id === 15) {
    assert.equal(blanks.length, 6);
    const byRow = {}, byCol = {};
    for (const n of blanks) {
      (byRow[rowOf(n)] = byRow[rowOf(n)] || []).push(n);
      (byCol[colOf(n)] = byCol[colOf(n)] || []).push(n);
    }
    const horiz = Object.values(byRow).find(group => group.length === 3);
    const vert = Object.values(byCol).find(group => group.length === 3);
    assert(horiz && vert, 'One horizontal run and one vertical run');
    horiz.sort((a, b) => a - b);
    vert.sort((a, b) => a - b);
    assert.equal(horiz[1] - horiz[0], 2, 'Horizontal skip: +2');
    assert.equal(horiz[2] - horiz[1], 2);
    assert.equal(vert[1] - vert[0], 20, 'Vertical skip: +20');
    assert.equal(vert[2] - vert[1], 20);
    assert.equal(new Set([...horiz, ...vert]).size, 6, 'The two runs do not overlap');
  } else assert.fail('Unexpected jump level: ' + level.id);
}

