// A separate, set/peer-based Sudoku solver, counting up to two completions.
// Its input contains zeroes in blanks and has no reference to answers or solved values.
function solveSudoku(input, size, boxRows, boxCols) {
  const board = input.slice();
  const domain = sequence(1, size);
  const units = [];
  for (let r = 0; r < size; r++) units.push(sequence(0, size - 1).map(c => r * size + c));
  for (let c = 0; c < size; c++) units.push(sequence(0, size - 1).map(r => r * size + c));
  for (let r = 0; r < size; r += boxRows) {
    for (let c = 0; c < size; c += boxCols) {
      const box = [];
      for (let dr = 0; dr < boxRows; dr++) {
        for (let dc = 0; dc < boxCols; dc++) box.push((r + dr) * size + c + dc);
      }
      units.push(box);
    }
  }
  for (const unit of units) {
    const values = unit.map(i => board[i]).filter(Boolean);
    if (new Set(values).size !== values.length || values.some(n => !domain.includes(n))) {
      return { count: 0, solution: null };
    }
  }
  const peers = board.map((_, i) => [...new Set(units.filter(u => u.includes(i)).flat())].filter(p => p !== i));
  let count = 0;
  let solution = null;
  function search() {
    if (count === 2) return;
    let target = -1;
    let options = null;
    for (let i = 0; i < board.length; i++) {
      if (board[i]) continue;
      const used = new Set(peers[i].map(p => board[p]));
      const allowed = domain.filter(n => !used.has(n));
      if (!allowed.length) return;
      if (options === null || allowed.length < options.length) {
        target = i;
        options = allowed;
      }
    }
    if (target === -1) {
      count++;
      if (!solution) solution = board.slice();
      return;
    }
    for (const value of options) {
      board[target] = value;
      search();
      board[target] = 0;
      if (count === 2) return;
    }
  }
  search();
  return { count, solution };
}

// Geometry intentionally differs from the production neighbor helper.
function adjacent(cell, size) {
  const row = Math.floor((cell - 1) / size);
  const col = (cell - 1) % size;
  const result = [];
  for (let r = Math.max(0, row - 1); r <= Math.min(size - 1, row + 1); r++) {
    for (let c = Math.max(0, col - 1); c <= Math.min(size - 1, col + 1); c++) {
      if (r !== row || c !== col) result.push(r * size + c + 1);
    }
  }
  return result;
}

// Independent proof checker: safe/mine facts follow only from visible-number equations
// and the published total. A deduced safe cell is NEVER used as a new numbered clue.
// Zero/full equations and subset differences are sound, so proving every status also
// proves a unique mine layout and, consequently, unique counts for all hidden safe cells.
function inferMines(size, visible, mineCount) {
  const cells = sequence(1, size * size);
  const facts = new Map(Object.keys(visible).map(key => [Number(key), 0]));
  const constraints = Object.entries(visible).map(([cell, value]) => ({
    cells: new Set(adjacent(Number(cell), size)), sum: value
  }));
  constraints.push({ cells: new Set(cells), sum: mineCount });
  let steps = 0;
  while (facts.size < cells.length) {
    const reduced = constraints.map(eq => ({
      cells: new Set([...eq.cells].filter(cell => !facts.has(cell))),
      sum: eq.sum - [...eq.cells].reduce((sum, cell) => sum + (facts.get(cell) || 0), 0)
    }));
    for (const eq of reduced) assert(eq.sum >= 0 && eq.sum <= eq.cells.size, 'Contradictory observations');
    const forced = new Map();
    function prove(set, sum) {
      assert(sum >= 0 && sum <= set.size, 'Contradictory difference');
      if (!set.size || (sum !== 0 && sum !== set.size)) return;
      const value = sum === 0 ? 0 : 1;
      for (const cell of set) {
        if (forced.has(cell)) assert.equal(forced.get(cell), value, 'Conflicting proof');
        forced.set(cell, value);
      }
    }
    for (const eq of reduced) prove(eq.cells, eq.sum);
    if (!forced.size) {
      for (const larger of reduced) {
        for (const smaller of reduced) {
          if (!smaller.cells.size || smaller.cells.size >= larger.cells.size) continue;
          const difference = new Set([...larger.cells].filter(cell => !smaller.cells.has(cell)));
          if (difference.size === larger.cells.size - smaller.cells.size) {
            prove(difference, larger.sum - smaller.sum);
          }
        }
      }
    }
    if (!forced.size) break;
    for (const [cell, value] of forced) facts.set(cell, value);
    steps++;
  }
  return { facts, steps };
}

function checkCandidates(level, remaining, target, seed) {
  const before = JSON.stringify(level);
  const previousRemaining = remaining.slice();
  const actual = plain(api.candidates(level, remaining, target, rng(seed)));
  assert.equal(actual.length, 10, `Ten candidates: level ${level.id}`);
  assert.equal(new Set(actual).size, 10, `Unique candidates: level ${level.id}`);
  assert(actual.every(Number.isInteger));
  assert(actual.includes(level.answers[target]), `Missing target ${target}: level ${level.id}`);
  assert.equal(JSON.stringify(level), before, 'Candidate refresh must not mutate the level');
  assert.deepEqual(remaining, previousRemaining, 'Candidate refresh must not mutate remaining IDs');
  if (level.kind === 'sudoku') assert.deepEqual(actual.slice().sort((a, b) => a - b), sequence(1, 10));
  else if (level.kind === 'mines') assert.deepEqual(actual.slice().sort((a, b) => a - b), sequence(-1, 8));
  else {
    const min = level.kind === 'prime' ? level.minNumber : 1;
    const max = level.kind === 'prime' ? level.maxNumber : level.kind === 'multiplication' ? 81 : 100;
    assert(actual.every(n => n >= min && n <= max), `Candidates stay in domain: ${level.id}`);
    const required = [...new Set([target, ...remaining].map(cell => level.answers[cell]))];
    if (required.length <= 10) {
      assert(required.every(n => actual.includes(n)), 'Switching between ten or fewer distinct answers needs no refresh');
    } else {
      assert.equal(actual.filter(n => required.includes(n)).length, 9, 'Nine required answers plus a distractor');
    }
  }
  assert.deepEqual(actual, plain(api.candidates(level, remaining, target, rng(seed))), 'Explicit RNG reproducibility');
  return actual;
}

