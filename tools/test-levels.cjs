  assert.deepEqual(level.knownPrimes, known, `Complete earlier highlights: ${id}`);
  assert.notStrictEqual(level.primeCells, level.knownPrimes);
  assert.deepEqual([...known, ...current], PRIMES.filter(n => n <= max));
